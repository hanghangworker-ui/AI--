const dicts: Record<Lang, Record<string, string>> = { zh, en }

export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? dicts.zh[key] ?? key
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v))
  return s
}

interface I18nCtx { lang: Lang; setLang: (l: Lang) => void; t: (k: string, p?: Record<string, string | number>) => string }
export const LangContext = createContext<I18nCtx>({ lang: 'zh', setLang: () => {}, t: (k) => k })

export const useI18n = () => useContext(LangContext)

export const LangProvider: React.FC<{ lang: Lang; setLang: (l: Lang) => void; children: React.ReactNode }> = ({ lang, setLang, children }) => {
  const t = (k: string, p?: Record<string, string | number>) => translate(lang, k, p)
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>
}
